
# Rainfall Volume Calculator
# My first water engineering project

rainfall_mm = 50
area_m2 = 1000

rainfall_volume_m3 = (rainfall_mm / 1000) * area_m2

print("Rainfall:", rainfall_mm, "mm")
print("Area:", area_m2, "m2")
print("Total rainfall volume:", rainfall_volume_m3, "m3")

print("Calculation complete!")
print("My first GitHub project is ready!")

# Calculate average rainfall intensity

duration_hours = 2
rainfall_intensity = rainfall_mm / duration_hours

print("Average rainfall intensity:", rainfall_intensity, "mm/h")
